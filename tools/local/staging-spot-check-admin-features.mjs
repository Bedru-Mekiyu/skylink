// LIGHT spot check on the test site only (bedru): home, About, Portfolio, the new admin pages and one delete flow on a test item.
//   BEDRU_ADMIN_EMAIL=... BEDRU_ADMIN_PASSWORD=... node tools/local/staging-spot-check-admin-features.mjs
import { chromium } from 'playwright-core';
import fs from 'node:fs';
import path from 'node:path';

const base = 'https://bedru.skylinkict.com';
const out = path.resolve('footage/_review/spot-bedru-admin-features');
fs.mkdirSync(out, { recursive: true });
const nap = (ms = 2500) => new Promise((r) => setTimeout(r, ms));
const results = []; const rec = (n, pass, note = '') => { results.push({ n, pass }); console.log(pass ? 'ok  ' : 'FAIL', n, note ? '- ' + note : ''); };
const browser = await chromium.launch();
const p = await (await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' })).newPage();
let loads = 0; const errs = [];
p.on('console', (m) => { if (m.type() === 'error' && !/tawk|ERR_FAILED|favicon|Failed to load resource/i.test(m.text())) errs.push(m.text().slice(0, 100)); });
const go = async (u) => { errs.length = 0; const r = await p.goto(base + u, { waitUntil: 'load', timeout: 60000 }); loads++; await p.waitForTimeout(1800); return r.status(); };
const ovf = () => p.evaluate(() => document.documentElement.scrollWidth - innerWidth);

await go('/');
const h = await p.evaluate(() => ({ ann: document.querySelector('.anniv5__title')?.textContent.trim() || '(ceremony hidden on this site)', tcards: document.querySelectorAll('#testimonials .testimonial-card').length, tnames: [...document.querySelectorAll('#testimonials .client-info h5')].slice(0, 6).map((e) => e.textContent).join(', '), years: document.querySelector('.stat-number')?.getAttribute('data-target') }));
rec('home: testimonial strip from the admin data (6 names, in order), years 5+, no errors', h.tcards >= 6 && /Ibrahim Mohammed, Aisha Malik/.test(h.tnames) && h.years === '5+' && !errs.length && (await ovf()) <= 0, JSON.stringify(h));
await nap();
await go('/about');
const a = await p.evaluate(() => ({ deps: [...document.querySelectorAll('#departments h3')].map((e) => e.textContent).join(', '), labels: /Achievements\/Features/.test(document.body.innerText), banner: document.querySelector('.about-hero__img')?.currentSrc.split('/').pop(), ovf: document.documentElement.scrollWidth - innerWidth }));
rec('About: two department cards from the admin, Milestones labels gone, cropped banner, no sideways scroll', a.deps === 'Software Team, Marketing Team' && !a.labels && /team-banner/.test(a.banner) && a.ovf <= 0 && !errs.length, JSON.stringify(a));
await p.screenshot({ path: path.join(out, 'about-top.png') });
await nap();
const ps = await go('/portfolio');
rec('Portfolio: banner shown (newest project rule), no errors', ps === 200 && (await p.locator('.pf-hero__title').count()) === 1 && !errs.length, await p.locator('.pf-hero__title').innerText());
await nap();
await go('/login');
await p.fill('input[name=email]', process.env.BEDRU_ADMIN_EMAIL); await p.fill('input[name=password]', process.env.BEDRU_ADMIN_PASSWORD);
await p.click('button[type=submit]'); await p.waitForURL(/admin/, { timeout: 20000 }).catch(() => {});
rec('admin login', /\/admin\//.test(p.url()));
await nap();
await go('/admin/testimonials');
rec('Admin > Testimonials lists the 6 imported ones', (await p.locator('tbody tr').count()) === 6 && (await ovf()) <= 0);
await p.screenshot({ path: path.join(out, 'admin-testimonials.png') });
await nap();
await go('/admin/testimonials/create');
await p.fill('#name', 'ZZ Spot Check Test'); await p.fill('#quote_en', 'Temporary test quote, removed right after.');
await p.click('button[type=submit]'); await p.waitForURL(/\/admin\/testimonials$/, { timeout: 20000 }).catch(() => {}); loads++;
rec('a test testimonial can be added', (await p.locator('tr', { hasText: 'ZZ Spot Check Test' }).count()) === 1 && (await p.locator('tbody tr').count()) === 7);
await nap();
const row = p.locator('tr', { hasText: 'ZZ Spot Check Test' });
await row.locator('button[aria-label^="Delete"]').click();
await p.waitForTimeout(800);
const modal = await p.evaluate(() => { const m = document.querySelector('.modal.show, [role=dialog]'); return m ? m.innerText.replace(/\s+/g, ' ').slice(0, 160) : ''; });
await p.screenshot({ path: path.join(out, 'delete-modal.png') });
rec('delete asks in an in-page modal that names the item', /ZZ Spot Check Test/.test(modal) && /removed for good/i.test(modal), modal);
await p.locator('.modal.show button.btn-danger, [role=dialog] button.btn-danger, .modal.show [data-sky-ok], [role=dialog] .sky-ok').first().click({ timeout: 8000 }).catch(async () => { await p.keyboard.press('Enter'); });
await p.waitForURL(/\/admin\/testimonials/, { timeout: 20000 }).catch(() => {}); await p.waitForTimeout(2000); loads++;
rec('the test testimonial is deleted (6 left again)', (await p.locator('tr', { hasText: 'ZZ Spot Check Test' }).count()) === 0 && (await p.locator('tbody tr').count()) === 6);
await nap();
await go('/admin/departments');
rec('Admin > Departments lists the 2 imported ones', (await p.locator('tbody tr').count()) === 2 && (await ovf()) <= 0);
console.log('page loads:', loads);
await browser.close();
const failed = results.filter((r) => !r.pass);
console.log(`\n${results.length - failed.length}/${results.length} passed`);
process.exit(failed.length ? 1 : 0);
